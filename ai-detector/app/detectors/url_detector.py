import requests
"""
URL Content Detection

Fetches content from URLs and analyzes for AI generation.

Use cases:
- Blog post analysis: Check if article was AI-written
- Social media: Analyze tweets, posts, comments
- News articles: Verify journalistic content authenticity
- Product descriptions: E-commerce AI-generated copy detection

Detection pipeline:
1. Fetch HTML from URL
2. Extract main content (skip nav, ads, footers)
3. Detect content type (text/image/video)
4. Route to appropriate detector
5. Return results with source URL

Web scraping considerations:
- User-Agent: Identify as SpotBot to be polite
- Respect robots.txt (TODO: Add robots.txt parser)
- Rate limiting: Don't hammer servers
- Timeout: 10 seconds max for fetch
- Error handling: 404, network errors, malformed HTML

Content extraction strategy:
- Use BeautifulSoup to parse HTML
- Extract <article>, <main>, or largest text block
- Remove boilerplate (nav, footer, ads)
- Preserve formatting for better detection
"""

from typing import Dict, Any
import requests
from bs4 import BeautifulSoup

class URLDetector:
    """
    URL content fetcher and AI detector.
    
    Fetches content from URLs and routes to appropriate detector based on content type.
    
    Features:
    - HTML parsing with BeautifulSoup
    - Content extraction (main text, images)
    - Auto-detection of content type
    - Error handling for network issues
    
    Limitations:
    - JavaScript-rendered content not supported (needs headless browser)
    - Paywalled content can't be accessed
    - Some sites block scrapers (captcha, rate limiting)
    
    Future improvements:
    - Add Selenium/Playwright for JS-rendered sites
    - Respect robots.txt
    - Add caching to avoid re-fetching
    - Extract structured data (OpenGraph, JSON-LD)
    """
    
    def __init__(self):
        self.headers = {
            'User-Agent': 'Mozilla/5.0 (SpotBot/1.0)'
        }
    
    def analyze(self, url: str) -> Dict[str, Any]:
        """Analyze content from URL"""
        try:
            # Fetch URL content
            response = requests.get(url, headers=self.headers, timeout=10)
            response.raise_for_status()
            
            # Parse HTML
            soup = BeautifulSoup(response.content, 'html.parser')
            
            # Extract text content
            # Remove script and style elements
            for script in soup(["script", "style"]):
                script.decompose()
            
            text = soup.get_text()
            lines = (line.strip() for line in text.splitlines())
            chunks = (phrase.strip() for line in lines for phrase in line.split("  "))
            text = ' '.join(chunk for chunk in chunks if chunk)
            
            # Analyze text using simple heuristics
            # In production, this would use the TextDetector class
            from app.detectors.text_detector import TextDetector
            text_detector = TextDetector()
            result = text_detector.analyze(text[:5000])  # Analyze first 5000 chars
            
            # Add URL-specific details
            result["analysis_details"]["url"] = url
            result["analysis_details"]["content_length"] = len(text)
            result["analysis_details"]["title"] = soup.title.string if soup.title else None
            
            # Check for AI content disclosure
            content_lower = text.lower()
            ai_disclosure_terms = [
                "generated by ai",
                "written by ai",
                "created with chatgpt",
                "assisted by ai",
                "ai-generated",
            ]
            
            has_disclosure = any(term in content_lower for term in ai_disclosure_terms)
            if has_disclosure:
                result["confidence_score"] = min(result["confidence_score"] + 30, 100)
                result["analysis_details"]["ai_disclosure_found"] = True
            
            return result
            
        except requests.RequestException as e:
            return {
                "is_ai_generated": None,
                "confidence_score": 0.0,
                "detected_model": None,
                "model_confidence": None,
                "analysis_details": {
                    "error": f"Failed to fetch URL: {str(e)}",
                    "url": url
                }
            }
        except Exception as e:
            return {
                "is_ai_generated": None,
                "confidence_score": 0.0,
                "detected_model": None,
                "model_confidence": None,
                "analysis_details": {
                    "error": f"Failed to analyze URL content: {str(e)}",
                    "url": url
                }
            }
